namespace one::generators {

    namespace agent_detail {

        struct found {
            const language::define_agent_declaration* agent;
            std::string ns, path;
        };

        struct flow {
            const language::define_workflow_declaration* workflow;
            std::string ns;
        };

        inline void collect(const std::vector<language::declaration>& declarations, const std::string& ns, const std::string& path,
                            std::vector<found>& agents, std::vector<flow>& flows, std::string& domain) {
            for (const auto& d : declarations) {
                if (auto* n = std::get_if<language::namespace_declaration>(&d.node)) {
                    collect(n->declarations, ns.empty() ? n->name : ns + "::" + n->name, path, agents, flows, domain);
                } else if (auto* a = std::get_if<language::define_agent_declaration>(&d.node)) {
                    agents.push_back({a, ns, path});
                } else if (auto* w = std::get_if<language::define_workflow_declaration>(&d.node)) {
                    flows.push_back({w, ns});
                } else if (auto* p = std::get_if<language::project_declaration>(&d.node)) {
                    for (const auto& s : p->settings) {
                        if (s.key == "domain") domain = s.value;
                    }
                }
            }
        }

        inline std::string str(std::string_view text) { return native_detail::literal(text); }

    }  // namespace agent_detail

    std::vector<output_file> generate_agents(const std::vector<language::file>& files) {
        using namespace agent_detail;
        std::vector<found> agents;
        std::vector<flow> flows;
        std::string domain;
        for (const auto& f : files) collect(f.declarations, "", f.path, agents, flows, domain);
        std::vector<output_file> out;
        std::string server = domain.empty() ? "http://localhost:8080" : "https://" + domain;
        for (const auto& [agent, ns, path] : agents) {
            const std::string& name = agent->name;
            auto in = [&](const std::string& word) { return ns.empty() ? word : ns + "::" + word; };

            code::stream main("\t");
            {
                auto from = main.from(path, agent->where.line);
                {
                    auto fixed = main.fixed();
                    main.line("// Generated by one. Do not edit.");
                }
                main.line("//");
                main.line("// " + name + ": works, as " + agent->role + ", the stages it names, by itself. It signs in with its");
                main.line("// service's key, ONE_KEY, at " + server + ", or ONE_SERVER.");
                main.line();
                main.line("#include <cstdlib>");
                main.line("#include <print>");
                main.line();
                main.line("#include <one/client/agent.hpp>");
                main.line();
                main.open("namespace {");
                main.line();
                main.open("std::string setting(const char* name, std::string otherwise) {");
                main.line("const char* given = std::getenv(name);");
                main.line("return given && *given ? given : otherwise;");
                main.close("}");
                main.line();
                main.close("}  // namespace");
                main.line();
                main.open("int main() {");
                main.line("one::client::agent " + native_detail::identifier(name) + "{.name = " + str(name) + "};");
            }
            for (const auto& rule : agent->rules) {
                auto from = main.from(path, rule.where.line);
                std::string along = "stage";
                int lease = 10;
                for (const auto& [w, flow_ns] : flows) {
                    if (flow_ns == ns && w->entity == rule.entity) along = w->by, lease = w->lease_minutes;
                }
                main.line(native_detail::identifier(name) + ".rules.push_back({.queue = " + str(in(rule.entity + "_work")) + ", .entity = " + str(in(rule.entity)) +
                          ", .along = " + str(along) + ", .stage = " + str(rule.stage) + ", .program = " + str(rule.program) + ", .then = " + str(rule.then) +
                          ", .otherwise = " + str(rule.otherwise) + ", .lease_minutes = " + std::to_string(lease) + "});");
            }
            {
                auto from = main.from(path, agent->where.line);
                main.line("ember::queue_executor loop;");
                main.line("std::string server = setting(\"ONE_SERVER\", " + str(server) + ");");
                main.line("one::client::session app({.server = server, .project = setting(\"ONE_FIREBASE_PROJECT\", \"\"), .firestore_host = setting(\"ONE_FIRESTORE_HOST\", \"\"),");
                main.line("                          .auth_host = setting(\"ONE_AUTH_HOST\", \"\")}, &loop);");
                main.line("std::string key = setting(\"ONE_KEY\", \"\");");
                main.open("if (key.empty()) {");
                main.line("std::println(stderr, \"" + name + ": say its service's key in ONE_KEY\");");
                main.line("return 1;");
                main.close("}");
                main.open("try {");
                main.line("app.sign_in_with_key(key);");
                main.line("return one::client::work(app, loop, " + native_detail::identifier(name) + ");");
                main.dedent();
                main.open("} catch (const std::exception& e) {");
                main.line("std::println(stderr, \"" + name + ": {}\", e.what());");
                main.line("return 1;");
                main.close("}");
                main.close("}");
            }

            code::stream cmake("\t");
            {
                auto from = cmake.from(path, agent->where.line);
                {
                    auto fixed = cmake.fixed();
                    cmake.line("# Generated by one. Do not edit.");
                }
                cmake.line();
                cmake.line("cmake_minimum_required(VERSION 3.28)");
                cmake.line("project(" + native_detail::identifier(name) + "_agent LANGUAGES CXX)");
                cmake.line();
                cmake.line("set(CMAKE_CXX_STANDARD 23)");
                cmake.line("set(CMAKE_CXX_STANDARD_REQUIRED ON)");
                cmake.line();
                cmake.line("# uione's client library: a checkout of uione named by UIONE, or the release installed");
                cmake.line("# with the compiler, in ~/.local/share/uione/" + std::string(version) + ".");
                cmake.line("set(UIONE \"\" CACHE PATH \"a checkout of uione, or its release's libraries\")");
                cmake.open("if(DEFINED ENV{UIONE} AND NOT \"$ENV{UIONE}\" STREQUAL \"\")");
                cmake.line("set(UIONE \"$ENV{UIONE}\")");
                cmake.close("endif()");
                cmake.open("if(NOT UIONE)");
                cmake.line("set(UIONE \"$ENV{HOME}/.local/share/uione/" + std::string(version) + "\")");
                cmake.close("endif()");
                cmake.line("add_subdirectory(${UIONE}/client ${CMAKE_BINARY_DIR}/uione-client EXCLUDE_FROM_ALL)");
                cmake.line();
                cmake.line("add_executable(" + name + " main.cpp)");
                cmake.line("target_link_libraries(" + name + " PRIVATE one_client)");
                cmake.line("target_compile_options(" + name + " PRIVATE -Wno-free-nonheap-object)");
            }
            out.push_back(file("agents/" + name + "/main.cpp", main));
            out.push_back(file("agents/" + name + "/CMakeLists.txt", cmake));
        }
        return out;
    }

}  // namespace one::generators
